void FramebufferConsole::drawPixel(uint32_t x, uint32_t y, uint32_t color)
{
    if (x >= fb->width || y >= fb->height) return;

    uint32_t* fbPtr = (uint32_t*)fb->address;
    uint64_t pitchPixels = fb->pitch / 4;

    fbPtr[y * pitchPixels + x] = color;
}

static FramebufferConsole globalConsole;

void FramebufferConsole::init(struct limine_framebuffer* framebuffer, uint32_t textColor, uint32_t backgroundColor)
{
    fb = framebuffer;
    cursorX = 10;
    cursorY = 10;
    fontColor = textColor;
    bgColor = backgroundColor;
}

void FramebufferConsole::putChar(char c)
{
    if (c == '\n') {
        cursorX = 10;
        cursorY += 12;
        return;
    }

    if (c == '\r') {
        cursorX = 10;
        return;
    }

    uint8_t ascii = (uint8_t)c;

    if (ascii < 32 || ascii > 126) return;

    if (cursorX + 8 >= fb->width) {
        cursorX = 10;
        cursorY += 12;
    }

    int fontIndex = ascii - 32;
    
    for (int y = 0; y < 8; y++) {
        uint8_t rowData = font8x8[fontIndex][y];
        
        for (int x = 0; x < 8; x++) {
            if (rowData & (0x80 >> x)) {
                drawPixel(cursorX + x, cursorY + y, fontColor);
            }
        }
    }

    cursorX += 8;
}

void FramebufferConsole::print(const char* str)
{
    if (!str) return;
    
    const char* p = str;
    while (*p != '\0') {
        putChar(*p);
        p++;
    }
}

extern "C" void printf(const char* str) {
    globalConsole.print(str);
}

extern "C" void init_printf(struct limine_framebuffer* fb, uint32_t text_color, uint32_t background_color) {
    globalConsole.init(fb, text_color, background_color);
}